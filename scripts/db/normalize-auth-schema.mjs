// Keep the generator's core fields; use instants consistently across auth and domain.
import { readFile, writeFile } from 'node:fs/promises';
const path = new URL('../../src/server/db/auth.generated.ts', import.meta.url);
const source = await readFile(path, 'utf8');
const normalized = source.replace(/timestamp\((['"][^'"]+['"])\)/g, 'timestamp($1, { withTimezone: true })');
await writeFile(path, '// Generated by auth@1.7.21; normalized to TIMESTAMPTZ. See docs/DATABASE.md.\n' + normalized);
